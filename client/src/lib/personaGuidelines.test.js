import test from 'node:test'
import assert from 'node:assert/strict'
import { guidelinePatches, guidelinesDraft, validAgeRange, newPersonaSlug, personaInitials } from './personaGuidelines.js'
import { validatePersonaFields } from './workspaceConfiguration.js'

const persona = { id: 'persona', name: 'The Business Owner', audience_profile: { custom: { preserve: true }, needs: ['Education'], ageRange: [35, 60] }, prompt_guidance: 'Explain clearly' }
const brand = { values: ['Transparency'], tone: { voice: 'Clear', professional: 2, custom: { preserve: true } } }

test('opening and confirming guidelines leaves existing data and unset fields unchanged', () => {
  const draft = guidelinesDraft(persona, brand)
  assert.deepEqual(guidelinePatches(persona, brand, draft), { personaPatch: {}, brandPatch: {} })
  const blank = { ...persona, audience_profile: {} }
  const fresh = guidelinesDraft(blank, { values: [], tone: {} })
  assert.deepEqual(guidelinePatches(blank, { values: [], tone: {} }, fresh), { personaPatch: {}, brandPatch: {} })
  assert.equal(fresh.tone.professional, undefined)
  assert.equal(JSON.parse(fresh.audienceRaw).ageRange, undefined)
})

test('legacy audience controls round-trip through current API fields while preserving unrelated JSON', () => {
  const draft = guidelinesDraft(persona, brand)
  draft.audienceRaw = JSON.stringify({ ...JSON.parse(draft.audienceRaw), ageRange: [25, 45], income: '$100k-$200k', education: "Bachelor's degree", pain_points: ['Documentation'] })
  const { personaPatch, brandPatch } = guidelinePatches(persona, brand, draft)
  assert.deepEqual(brandPatch, {})
  assert.deepEqual(personaPatch.audience_profile.custom, { preserve: true })
  assert.deepEqual(personaPatch.audience_profile.ageRange, [25, 45])
  assert.equal(personaPatch.audience_profile.income, '$100k-$200k')
  assert.deepEqual(validatePersonaFields(personaPatch), personaPatch)
  assert.deepEqual(persona.audience_profile.ageRange, [35, 60])
})

test('number choices and core values patch shared brand only without changing voice or identity', () => {
  const draft = guidelinesDraft(persona, brand)
  draft.tone = { ...draft.tone, professional: 5, serious: 3 }
  draft.coreValues = 'Transparency\nAccuracy'
  const { personaPatch, brandPatch } = guidelinePatches(persona, brand, draft)
  assert.deepEqual(personaPatch, {})
  assert.deepEqual(brandPatch.values, ['Transparency', 'Accuracy'])
  assert.equal(brandPatch.tone.voice, 'Clear')
  assert.deepEqual(brandPatch.tone.custom, { preserve: true })
  assert.equal(brand.tone.professional, 2)
  assert.equal(brandPatch.nmls_id, undefined)
  delete draft.tone.professional
  assert.equal(guidelinePatches(persona, brand, draft).brandPatch.tone.professional, undefined)
})

test('custom audience field shapes stay intact until deliberately edited and invalid JSON cannot save', () => {
  const custom = { ...persona, audience_profile: { needs: { custom: 'shape' }, ageRange: 'legacy', income: { currency: 'custom' } } }
  const draft = guidelinesDraft(custom, brand)
  draft.guidance = 'New communication guidance'
  assert.deepEqual(guidelinePatches(custom, brand, draft).personaPatch, { prompt_guidance: 'New communication guidance' })
  draft.audienceRaw = '{invalid'
  assert.throws(() => guidelinePatches(custom, brand, draft), /valid audience JSON/)
})

test('range bounds and autogenerated persona identifiers match legacy controls and current contracts', () => {
  assert.equal(validAgeRange([1, 100]), true)
  assert.equal(validAgeRange([45, 45]), true)
  for (const value of [[60, 35], [0, 100], [1, 101], ['25', 45], [25], null]) assert.equal(validAgeRange(value), false)
  for (const name of ['The Business Owner', 'Éducation', '🏡', 'x'.repeat(200)]) {
    const slug = newPersonaSlug(name)
    assert.equal(validatePersonaFields({ name, slug }).slug, slug)
  }
  assert.equal(personaInitials('The Business Owner'), 'BO')
})
